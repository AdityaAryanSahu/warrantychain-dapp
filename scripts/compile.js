// Compiles contracts/WarrantyChain.sol with solc-js and writes:
//   build/WarrantyChain.json  -> { abi, bytecode }   (used by the automated tests)
//   frontend/abi.js           -> window.WARRANTY_CHAIN_ABI (used by the DApp UI)
//
// Usage: npm run compile
//
// EVM version is pinned to "paris" so the bytecode runs on Ganache as well as
// on public testnets. Use the same setting in Remix (Compiler > Advanced
// Configurations > EVM Version > paris).

const fs = require("fs");
const path = require("path");
const solc = require("solc");

const ROOT = path.join(__dirname, "..");
const SOURCE_PATH = path.join(ROOT, "contracts", "WarrantyChain.sol");

const input = {
  language: "Solidity",
  sources: { "WarrantyChain.sol": { content: fs.readFileSync(SOURCE_PATH, "utf8") } },
  settings: {
    evmVersion: "paris",
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));

const errors = (output.errors || []).filter((e) => e.severity === "error");
(output.errors || []).forEach((e) => console.log(e.formattedMessage));
if (errors.length) {
  console.error("Compilation failed.");
  process.exit(1);
}

const contract = output.contracts["WarrantyChain.sol"].WarrantyChain;
const artifact = { abi: contract.abi, bytecode: "0x" + contract.evm.bytecode.object };

fs.mkdirSync(path.join(ROOT, "build"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "build", "WarrantyChain.json"), JSON.stringify(artifact, null, 2));
fs.writeFileSync(
  path.join(ROOT, "frontend", "abi.js"),
  "// Auto-generated by scripts/compile.js - do not edit by hand.\n" +
    "window.WARRANTY_CHAIN_ABI = " + JSON.stringify(contract.abi, null, 2) + ";\n"
);

console.log(`Compiled with solc ${solc.version()}`);
console.log(`ABI entries: ${contract.abi.length}, bytecode size: ${contract.evm.bytecode.object.length / 2} bytes`);
